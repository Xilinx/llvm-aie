// Structure representing an operand register class requirement for schedule
// variant matching. This is used by generated code from TableGen.
struct OperandRCRequirement {
  unsigned OpIdx;
  const TargetRegisterClass *RC;
};

// Structure representing an operand's register information for schedule
// variant matching. This abstracts the MachineOperand to allow callers to
// provide register class information directly without needing MachineOperands.
struct OperandRegInfo {
  Register Reg;
  const TargetRegisterClass *RC;

  OperandRegInfo() : Reg(), RC(nullptr) {}

  // Convenience constructor for physical register (RC will be null).
  explicit OperandRegInfo(Register R) : Reg(R), RC(nullptr) {}

  // Convenience constructor for register class (Reg will be invalid).
  explicit OperandRegInfo(const TargetRegisterClass *RegClass)
      : Reg(), RC(RegClass) {}

  // Full constructor with both Register and RegisterClass.
  OperandRegInfo(Register R, const TargetRegisterClass *RegClass)
      : Reg(R), RC(RegClass) {}
};

// Structure representing a schedule class variant.
struct SchedVariantInfo {
  unsigned SchedClass;
  llvm::ArrayRef<OperandRCRequirement> OperandRCs;
};

// Structure mapping an instruction to its schedule class variants.
struct InstrVariantInfo {
  unsigned Opcode;
  llvm::ArrayRef<SchedVariantInfo> Variants;
};

// Interface object that carries references to variable itinerary tables.
// This is used to look up schedule classes based on operand register classes.
// Generated by TableGen's AIEVariableInstrItineraryEmitter.
struct VarItinInterface {
  llvm::ArrayRef<InstrVariantInfo> InstrVariants;

  // Returns true if this interface has any variant data.
  bool hasVariants() const { return !InstrVariants.empty(); }
};

