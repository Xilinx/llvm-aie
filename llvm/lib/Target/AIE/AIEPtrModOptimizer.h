#ifndef LLVM_LIB_TARGET_AIE_AIEPTRMODOPTIMIZERPASS_H
#define LLVM_LIB_TARGET_AIE_AIEPTRMODOPTIMIZERPASS_H

#include "AIE.h"
#include "AIEGlobalCombiner.h"
#include "llvm/CodeGen/MachineFunction.h"
#include "llvm/CodeGen/MachineFunctionPass.h"
#include "llvm/CodeGen/MachineModuleInfo.h"
#include "llvm/InitializePasses.h"

using namespace llvm;

namespace llvm::AIE {

class FoundCombiners {
  // Whether FoundCombiners has been generated by an Analysis Pass
  bool GeneratedFromAnalysisPass = false;
  /// Map between CombineRoot and the corresponding Combiner
  std::map<MachineInstr *, Combiner> InstrCombines;

  /// Keep track for which MBB Combiners were found
  std::set<MachineBasicBlock *> MBBWithSolution;

  /// The keys are to be replaced MachineInstructions, and the values the newly
  /// inserted Instructions.
  std::map<MachineInstr *, MachineInstr *> ConvertedInstrs;

  /// If a MachineInstr is remapped to a new Instruction through a previous
  /// Combiner, update the MachineInstr and \return valid MachineInstructions
  std::vector<MachineInstr *>
  getRemappedInstrs(std::vector<MachineInstr *> &MIs) const;

  /// remap all the instruction of \p Combiner to valid instructions
  void remapCombiner(Combiner &Combiner) const;

public:
  FoundCombiners() {}
  FoundCombiners(bool Analysis) : GeneratedFromAnalysisPass(Analysis) {}
  FoundCombiners(FoundCombiners &Arg) = delete;
  ~FoundCombiners() = default;

  /// Add \p Combiner
  void append(const Combiner &CombineResult);

  /// \return Combiner to the \p CombineRoot
  Combiner *getCombine(MachineInstr *CombineRoot);

  /// Create Mapping between \p ReplacedMI and \p NewlyInsertedMI
  void createMapping(MachineInstr *ReplacedMI, MachineInstr *NewlyInsertedMI);

  /// \return newly Inserted Instruction of \p ReplaceMI
  MachineInstr *getMappedInstr(MachineInstr *ReplacedMI) const;

  const std::map<MachineInstr *, Combiner> &getInstrCombines() const;

  /// \return whether Analysis Pass generated this Object
  bool hasAnalysis() const { return GeneratedFromAnalysisPass; }
};
} // namespace llvm::AIE

namespace llvm {
raw_ostream &operator<<(raw_ostream &OS, const AIE::FoundCombiners &Val);

class AIEPtrModOptimizer : public llvm::MachineFunctionPass {
  std::unique_ptr<AIE::FoundCombiners> PtrModRes;

public:
  static char ID;
  AIEPtrModOptimizer() : MachineFunctionPass(ID) {}

  bool runOnMachineFunction(MachineFunction &MF) override;

  void getAnalysisUsage(AnalysisUsage &AU) const override;

  StringRef getPassName() const override;

  AIE::FoundCombiners *getGlobalPtrCombiners() { return PtrModRes.get(); }

private:
  void appendResult(std::vector<const AIE::GenericCombiner *> &Combiners);
};
} // namespace llvm

#endif // LLVM_LIB_TARGET_AIE_AIEPTRMODOPTIMIZERPASS_H
