#ifndef LLVM_LIB_TARGET_AIE2P_AIE2PSUBTARGET_H
#define LLVM_LIB_TARGET_AIE2P_AIE2PSUBTARGET_H
#include "AIE2P.h"
#include "AIE2PFrameLowering.h"
#include "AIE2PISelLowering.h"
#include "AIE2PInstrInfo.h"
#include "AIE2PRegisterInfo.h"
#include "AIE2Subtarget.h"
#include "llvm/CodeGen/GlobalISel/CallLowering.h"
#include "llvm/CodeGen/GlobalISel/InstructionSelector.h"
#include "llvm/CodeGen/GlobalISel/LegalizerInfo.h"

#define GET_SUBTARGETINFO_HEADER
#include "AIE2PGenSubtargetInfo.inc"

namespace llvm {
class StringRef;

class AIE2PSubtarget : public AIE2PGenSubtargetInfo, public AIEBaseSubtarget {
  virtual void anchor();
  std::string CPUName;
  // FIXME: Do we need a custom AIE2PAddrSpaceInfo?
  AIE2AddrSpaceInfo AddrSpaceInfo;
  AIE2PFrameLowering FrameLowering;
  AIE2PInstrInfo InstrInfo;
  AIE2PRegisterInfo RegInfo;
  AIE2PTargetLowering TLInfo;
  InstrItineraryData InstrItins;
  SelectionDAGTargetInfo TSInfo;

  /// Initializes using the passed in CPU and feature strings so that we can
  /// use initializer lists for subtarget initialization.
  AIE2PSubtarget &initializeSubtargetDependencies(const Triple &TT,
                                                  StringRef CPU, StringRef FS,
                                                  StringRef ABIName);

public:
  // Initializes the data members to match that of the specified triple.
  AIE2PSubtarget(const Triple &TT, StringRef CPU, StringRef TuneCPU,
                 StringRef FS, StringRef ABIName, const TargetMachine &TM);
  bool enableMachineScheduler() const override { return true; }
  bool enablePostRAScheduler() const override { return true; }
  bool enablePostRAMachineScheduler() const override { return true; }
  bool forcePostRAScheduling() const override { return true; }
  bool useAA() const override { return true; }

  CodeGenOptLevel getOptLevelToEnablePostRAScheduler() const override {
    // AIEngine hack: we currently rely on the post-RA scheduler to insert
    // NoOps for correcteness, make sure it runs even when the opt level is -O0.
    return CodeGenOptLevel::None;
  }

  void overrideSchedPolicy(MachineSchedPolicy &Policy,
                           unsigned NumRegionInstrs) const override {
    AIEBaseSubtarget::overrideSchedPolicyBase(Policy, NumRegionInstrs);
  }
  // Parses features string setting specified subtarget options. The
  // definition of this function is auto-generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  const AIE2PFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const InstrItineraryData *getInstrItineraryData() const override {
    return &InstrItins;
  }
  const AIE2PInstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const AIE2PRegisterInfo *getRegisterInfo() const override { return &RegInfo; }
  const AIE2PTargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }
  const SelectionDAGTargetInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }

  // Perform target-specific adjustments to the latency of a schedule
  // dependency.
  // If a pair of operands is associated with the schedule dependency, DefOpIdx
  // and UseOpIdx are the indices of the operands in Def and Use, respectively.
  // Otherwise, either may be -1.
  void
  adjustSchedDependency(SUnit *Def, int DefOpIdx, SUnit *Use, int UseOpIdx,
                        SDep &Dep,
                        const TargetSchedModel *SchedModel) const override {
    AIEBaseSubtarget::adjustSchedDependency(InstrItins, Def, DefOpIdx, Use,
                                            UseOpIdx, Dep);
  }
  void getPostRAMutations(std::vector<std::unique_ptr<ScheduleDAGMutation>>
                              &Mutations) const override {
    Mutations = AIEBaseSubtarget::getPostRAMutationsImpl(getTargetTriple());
  }
  void getSMSMutations(std::vector<std::unique_ptr<ScheduleDAGMutation>>
                           &Mutations) const override {
    Mutations = AIEBaseSubtarget::getSMSMutationsImpl(getTargetTriple());
  }

  // Finer-grained live ranges, giving more accurate use-def chains.
  bool enableSubRegLiveness() const override { return true; }

  /// Find the target operand flags that describe how a global value should be
  /// referenced for the current subtarget.
  unsigned classifyGlobalReference(const GlobalValue *GV,
                                   const TargetMachine &TM) const {
    if (!TM.shouldAssumeDSOLocal(GV)) {
      return AIEII::MO_GLOBAL;
    }
    return AIEII::MO_None;
  }

protected:
  // GlobalISel related APIs.
  std::unique_ptr<CallLowering> CallLoweringInfo;
  std::unique_ptr<LegalizerInfo> Legalizer;
  std::unique_ptr<RegisterBankInfo> RegBankInfo;
  std::unique_ptr<InstructionSelector> InstSelector;

public:
  const CallLowering *getCallLowering() const override;
  const LegalizerInfo *getLegalizerInfo() const override;
  const RegisterBankInfo *getRegBankInfo() const override;
  InstructionSelector *getInstructionSelector() const override;
  const AIEBaseAddrSpaceInfo &getAddrSpaceInfo() const override;
};

} // namespace llvm

#endif
