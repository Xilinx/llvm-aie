"""A test case update script for optimization remark (ORE) CHECK lines.

This script updates FileCheck assertions that verify -pass-remarks-output=-
YAML output in LLVM .ll and .mir test files.  It leaves non-remark CHECK
lines (e.g. assembly checks under a different prefix) untouched.

With --update-llc-checks or --update-mir-checks, the script first invokes
update_llc_test_checks.py or update_mir_test_checks.py to regenerate
assembly CHECK lines, then performs its own remark processing on top.

Usage:
    python3 update_ore_test_checks.py [--llc-binary /path/to/llc] [--update-llc-checks | --update-mir-checks] test1.ll ...
"""

from __future__ import print_function

import argparse
import os
import re
import shlex
import subprocess
import sys

from UpdateTestChecks import common

# ---------------------------------------------------------------------------
# Regexes
# ---------------------------------------------------------------------------

# Detects a RUN line whose llc invocation writes remarks to stdout.
PASS_REMARKS_OUTPUT_RE = re.compile(r"(?:^|\s)-pass-remarks-output(?:=|\s+)-(?=\s|$)")

# Matches a single YAML remark block emitted by -pass-remarks-output=-.
REMARK_BLOCK_RE = re.compile(
    r"^--- !(?P<kind>\w+)\n" r"(?P<body>.*?)\n" r"^\.\.\.$",
    flags=(re.M | re.S),
)

# Extracts the Function field from a remark body.
REMARK_FUNCTION_RE = re.compile(r"^Function:\s*(?P<func>[A-Za-z0-9_.$-]+)\s*$", re.M)

# Matches a FileCheck directive line.
CHECK_RE = re.compile(
    r"^\s*(?://|[;#])\s*([^:]+?)(?:-(NEXT|NOT|DAG|LABEL|SAME|EMPTY))?:"
)

# For extracting --check-prefix / --check-prefixes from a FileCheck command.
CHECK_PREFIX_RE = re.compile(r"--?check-prefix(?:es)?[= ](\S+)")

# IR function definition (opening brace on the same line).
IR_FUNC_DEF_RE = re.compile(r'^\s*define\s+[^@]*@"?(?P<func>[A-Za-z0-9_.$-]+)"?\s*\(')

# MIR function name.
MIR_FUNC_NAME_RE = re.compile(r"^name:\s*(?P<func>\S+)")

# MIR body start.
MIR_BODY_RE = re.compile(r"^body:\s*\|")

# MIR basic-block label.
MIR_BB_RE = re.compile(r"^\s+bb\.\d+")

UTC_ADVERT = "NOTE: Assertions have been autogenerated by "
SCRIPT_NAME = "utils/update_ore_test_checks.py"
UTC_ARGS_KEY = "UTC_ARGS:"
UTC_ARGS_RE = re.compile(r".*" + UTC_ARGS_KEY + r"\s*(?P<cmd>.*)\s*$")
UNUSED_NOTE = "NOTE: These prefixes are unused and the list is autogenerated. Do not add tests below this line:"

# Maps flag name to sibling script filename.
ASM_SCRIPT_MAP = {
    "update_llc_checks": "update_llc_test_checks.py",
    "update_mir_checks": "update_mir_test_checks.py",
}


# ---------------------------------------------------------------------------
# UTC_ARGS support
# ---------------------------------------------------------------------------


def build_autogenerated_note(comment_marker, asm_flag):
    """Build the NOTE line, appending UTC_ARGS when non-default flags are set.

    *asm_flag* is the dest name of the active flag (e.g. "update_llc_checks")
    or None.
    """
    note = comment_marker + " " + UTC_ADVERT + SCRIPT_NAME
    if asm_flag:
        # Convert dest name back to CLI flag: update_llc_checks -> --update-llc-checks
        flag = "--" + asm_flag.replace("_", "-")
        note += " " + UTC_ARGS_KEY + " " + flag
    return note


def parse_utc_args(first_line):
    """Extract --update-llc-checks or --update-mir-checks from UTC_ARGS."""
    if SCRIPT_NAME not in first_line:
        return None
    m = UTC_ARGS_RE.match(first_line)
    if not m:
        return None
    tokens = shlex.split(m.group("cmd").strip())
    if "--update-llc-checks" in tokens:
        return "update_llc_checks"
    if "--update-mir-checks" in tokens:
        return "update_mir_checks"
    return None


# ---------------------------------------------------------------------------
# Remark parsing
# ---------------------------------------------------------------------------


def parse_remarks(raw_output):
    """Parse YAML remark blocks from raw llc output.

    Returns {func_name: [[line, ...], ...]} where each inner list is one
    YAML block (including the ``--- !Kind`` opener and the ``...`` closer).
    """
    result = {}
    for m in REMARK_BLOCK_RE.finditer(raw_output):
        kind = m.group("kind")
        body = m.group("body")
        fm = REMARK_FUNCTION_RE.search(body)
        if not fm:
            continue
        func = fm.group("func")
        block_lines = ["--- !{}".format(kind)] + body.splitlines() + ["..."]
        result.setdefault(func, []).append(block_lines)
    return result


# ---------------------------------------------------------------------------
# CHECK-line generation
# ---------------------------------------------------------------------------


def generate_check_lines(comment_marker, prefix, blocks):
    """Return a list of CHECK / CHECK-NEXT lines for *blocks*.

    Each YAML block starts a fresh ``PREFIX:`` anchor so that FileCheck can
    scan forward between blocks.  Lines within a block use ``PREFIX-NEXT:``.
    """
    lines = []
    for block in blocks:
        first = True
        for text in block:
            directive = prefix if first else prefix + "-NEXT"
            first = False
            lines.append("{} {}: {}".format(comment_marker, directive, text))
    return lines


# ---------------------------------------------------------------------------
# RUN-line helpers
# ---------------------------------------------------------------------------


def get_check_prefixes(filecheck_cmd):
    """Extract FileCheck prefixes, defaulting to CHECK."""
    prefixes = [
        item
        for m in CHECK_PREFIX_RE.finditer(filecheck_cmd)
        for item in m.group(1).split(",")
    ]
    return prefixes if prefixes else ["CHECK"]


def split_pipeline(run_line):
    """Split a RUN line into pipeline stages, respecting shell quoting.

    A bare ``|`` inside single- or double-quoted strings is NOT treated
    as a pipeline separator.
    """
    stages = []
    current = []
    in_single = False
    in_double = False
    i = 0
    chars = run_line
    while i < len(chars):
        c = chars[i]
        if c == "'" and not in_double:
            in_single = not in_single
            current.append(c)
        elif c == '"' and not in_single:
            in_double = not in_double
            current.append(c)
        elif c == "\\" and i + 1 < len(chars):
            current.append(c)
            current.append(chars[i + 1])
            i += 1
        elif c == "|" and not in_single and not in_double:
            stages.append("".join(current).strip())
            current = []
        else:
            current.append(c)
        i += 1
    tail = "".join(current).strip()
    if tail:
        stages.append(tail)
    return stages


def has_asm_run_lines(run_lines):
    """True if any RUN line is a non-remark run the sibling asm/MIR update
    script can regenerate. A test whose RUN lines are all remark runs has no
    assembly to update, so the sibling script must not be invoked on it (after
    the remark runs are stripped it would see a file with no RUN lines)."""
    return any(not PASS_REMARKS_OUTPUT_RE.search(rl) for rl in run_lines)


def parse_remark_runs(run_lines, test_path):
    """Identify RUN lines that produce remark YAML output.

    Returns [(llc_cmd, [prefix, ...]), ...] for each remark run.
    """
    remark_runs = []
    for run_line in run_lines:
        if not PASS_REMARKS_OUTPUT_RE.search(run_line):
            continue

        stages = split_pipeline(run_line)
        if len(stages) < 2:
            continue

        llc_cmd = stages[0]
        filecheck_cmd = stages[-1]

        prefixes = get_check_prefixes(filecheck_cmd)
        remark_runs.append((llc_cmd, prefixes))
    return remark_runs


def run_llc(llc_cmd, llc_binary, test_path):
    """Execute the llc command and return its stdout as a string.

    Applies the standard lit path substitutions (%s, %S, %p, %{pathsep})
    via :func:`UpdateTestChecks.common.applySubstitutions` so RUN lines
    using more than just %s work correctly. Optionally overrides the
    llc binary.
    """
    cmd = common.applySubstitutions(llc_cmd, common.getPathSubstitutions(test_path))

    # Override llc binary if requested.
    if llc_binary:
        parts = cmd.split(None, 1)
        cmd = llc_binary + (" " + parts[1] if len(parts) > 1 else "")

    result = subprocess.run(cmd, shell=True, capture_output=True, text=True)
    if result.returncode != 0:
        print(
            "llc failed (exit {}): {}".format(result.returncode, cmd), file=sys.stderr
        )
        if result.stderr:
            print(result.stderr, file=sys.stderr)
        sys.exit(1)

    return result.stdout


# ---------------------------------------------------------------------------
# Assembly update script chaining
# ---------------------------------------------------------------------------


def invoke_asm_update_script(test_path, llc_binary, asm_flag):
    """Invoke update_llc_test_checks.py or update_mir_test_checks.py.

    Before calling the sibling script, the NOTE line and all remark
    RUN lines are stripped from the file.  This prevents the sibling
    from parsing our UTC_ARGS and from trying to process remark-only
    RUN lines (which would crash update_mir_test_checks.py).
    ``--force-update`` is used because the NOTE line references this
    script.
    """
    script_name = ASM_SCRIPT_MAP[asm_flag]
    script_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), script_name)

    # Strip our NOTE line and remark RUN lines so the sibling script
    # does not choke on our UTC_ARGS or on remark-only RUN lines.
    # Multi-line RUN groups (joined by backslash continuation) are
    # identified by joining them first, then checking for the remark
    # flag, and marking all contributing raw lines for removal.
    # After the sibling script finishes, the remark RUN lines are
    # restored so subsequent ore processing can find them.
    with open(test_path) as f:
        raw_lines = [l.rstrip() for l in f]

    # Identify line indices belonging to remark RUN groups.
    remark_line_indices = set()
    run_re = re.compile(r"^\s*(?://|[;#])\s*RUN:\s*(.*)$")
    i = 0
    while i < len(raw_lines):
        m = run_re.match(raw_lines[i])
        if not m:
            i += 1
            continue
        group_start = i
        joined = m.group(1)
        while joined.endswith("\\") and i + 1 < len(raw_lines):
            joined = joined[:-1]
            i += 1
            m2 = run_re.match(raw_lines[i])
            if m2:
                joined += " " + m2.group(1)
            else:
                break
        if PASS_REMARKS_OUTPUT_RE.search(joined):
            for j in range(group_start, i + 1):
                remark_line_indices.add(j)
        i += 1

    # Strip our NOTE and remark RUN lines for the sibling, recording for each
    # remark line how many surviving lines precede it: the sibling preserves
    # surviving lines in order, so this is its reinsertion offset.
    remark_sorted = sorted(remark_line_indices)
    kept_before = {}
    kept_count = 0
    with open(test_path, "w") as f:
        for idx, line in enumerate(raw_lines):
            if idx in remark_line_indices:
                kept_before[idx] = kept_count
                continue
            if SCRIPT_NAME in line:
                continue
            f.write(line + "\n")
            kept_count += 1

    cmd = [sys.executable, script_path, "--force-update"]
    if llc_binary:
        cmd.extend(["--llc-binary", llc_binary])
    cmd.append(test_path)

    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode != 0:
        print(
            "{} failed (exit {}):".format(script_name, result.returncode),
            file=sys.stderr,
        )
        if result.stderr:
            print(result.stderr, file=sys.stderr)
        sys.exit(1)

    # Reinsert each remark line at its original offset among the surviving
    # lines, past the sibling's leading NOTE line(s).
    with open(test_path) as f:
        updated_lines = [l.rstrip() for l in f]

    leading = 0
    while leading < len(updated_lines) and UTC_ADVERT in updated_lines[leading]:
        leading += 1

    for offset, j in enumerate(remark_sorted):
        insert_at = min(leading + kept_before[j] + offset, len(updated_lines))
        updated_lines.insert(insert_at, raw_lines[j])

    with open(test_path, "w") as f:
        for line in updated_lines:
            f.write(line + "\n")


# ---------------------------------------------------------------------------
# File updating
# ---------------------------------------------------------------------------


def is_check_line_for_prefix(line, prefix_set):
    """True if *line* is a CHECK directive for any prefix in *prefix_set*."""
    m = CHECK_RE.match(line)
    return bool(m and m.group(1) in prefix_set)


def strip_unused_prefix_note(lines):
    """Remove the trailing unused-prefix note left by update_llc_test_checks.py.

    The note is a double-comment line followed by zero or more
    ``; PREFIX: {{.*}}`` lines at the end of the file.
    """
    end = len(lines)
    while end > 0 and lines[end - 1].strip() == "":
        end -= 1

    # Strip trailing CHECK lines for unused prefixes.
    while end > 0 and CHECK_RE.match(lines[end - 1]):
        end -= 1

    # Strip the unused-prefix note itself.
    if end > 0 and UNUSED_NOTE in lines[end - 1]:
        end -= 1

    while end > 0 and lines[end - 1].strip() == "":
        end -= 1

    return lines[:end]


def update_ll_file(input_lines, remark_checks, remark_prefixes, note):
    """Rebuild a .ll file with updated remark CHECK lines.

    *remark_checks* maps func_name -> [check_line, ...].
    """
    output = []

    first = input_lines[0] if input_lines else ""
    if UTC_ADVERT in first:
        output.append(note)
        input_lines = input_lines[1:]
    else:
        output.append(note)

    for line in input_lines:
        # Strip old remark CHECK lines.
        if is_check_line_for_prefix(line, remark_prefixes):
            continue

        output.append(line)

        # After opening brace of a function definition, insert checks.
        fm = IR_FUNC_DEF_RE.match(line)
        if fm:
            func = fm.group("func")
            checks = remark_checks.get(func, [])
            output.extend(checks)

    return strip_unused_prefix_note(output)


def update_mir_file(input_lines, remark_checks, remark_prefixes, note):
    """Rebuild a .mir file with updated remark CHECK lines.

    Remark CHECK lines are placed inside each function's ``body: |`` block,
    right before the first ``bb.N`` line.
    """
    output = []

    first = input_lines[0] if input_lines else ""
    if UTC_ADVERT in first:
        output.append(note)
        input_lines = input_lines[1:]
    else:
        output.append(note)

    current_func = None
    in_body = False
    checks_inserted = False

    for line in input_lines:
        # Track current MIR function.
        fm = MIR_FUNC_NAME_RE.match(line)
        if fm:
            current_func = fm.group("func")
            in_body = False
            checks_inserted = False

        # Detect body: | start.
        if MIR_BODY_RE.match(line):
            in_body = True

        # Strip old remark CHECK lines.
        if is_check_line_for_prefix(line, remark_prefixes):
            continue

        # Insert checks before the first bb.N in the body.
        if in_body and not checks_inserted and MIR_BB_RE.match(line):
            checks = remark_checks.get(current_func, [])
            output.extend(checks)
            checks_inserted = True

        output.append(line)

    return strip_unused_prefix_note(output)


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--llc-binary",
        default=None,
        help='The "llc" binary to use to generate remarks',
    )

    asm_group = parser.add_mutually_exclusive_group()
    asm_group.add_argument(
        "--update-llc-checks",
        action="store_true",
        default=False,
        help="Invoke update_llc_test_checks.py to regenerate assembly "
        "CHECK lines before remark processing",
    )
    asm_group.add_argument(
        "--update-mir-checks",
        action="store_true",
        default=False,
        help="Invoke update_mir_test_checks.py to regenerate MIR "
        "CHECK lines before remark processing",
    )

    parser.add_argument(
        "--version",
        type=int,
        default=1,
        help="Compatibility flag (ignored). Accepted because lit.local.cfg "
        "passes --version=1 to all update scripts so that the version "
        "embedded in UTC_ARGS does not change in test expectations "
        "every time the default is bumped.",
    )
    parser.add_argument("tests", nargs="+", help="Test files to update")
    args = parser.parse_args()

    for test_path in args.tests:
        with open(test_path) as f:
            input_lines = [l.rstrip() for l in f]

        # Determine asm update flag: CLI takes precedence, then UTC_ARGS.
        first_line = input_lines[0] if input_lines else ""
        if args.update_llc_checks:
            asm_flag = "update_llc_checks"
        elif args.update_mir_checks:
            asm_flag = "update_mir_checks"
        else:
            asm_flag = parse_utc_args(first_line)

        run_lines = common.find_run_lines(test_path, input_lines)

        # Regenerate assembly CHECK lines first, but only when there is a
        # non-remark RUN line to regenerate. Delegating for a remark-only test
        # would hand the sibling script a file with no RUN lines.
        if asm_flag and has_asm_run_lines(run_lines):
            invoke_asm_update_script(test_path, args.llc_binary, asm_flag)

            # Re-read the file (and its RUN lines) after the asm script rewrote it.
            with open(test_path) as f:
                input_lines = [l.rstrip() for l in f]
            run_lines = common.find_run_lines(test_path, input_lines)

        remark_runs = parse_remark_runs(run_lines, test_path)

        if not remark_runs:
            print("No remark RUN lines found in {}".format(test_path), file=sys.stderr)
            continue

        is_mir = test_path.endswith(".mir")
        comment_marker = "  ;" if is_mir else ";"
        file_comment = "#" if is_mir else ";"
        note = build_autogenerated_note(file_comment, asm_flag)

        # Collect remarks from all remark runs.
        all_remark_prefixes = set()
        remark_checks = {}  # func -> [check_line, ...]

        for llc_cmd, prefixes in remark_runs:
            all_remark_prefixes.update(prefixes)

            raw_output = run_llc(llc_cmd, args.llc_binary, test_path)
            func_remarks = parse_remarks(raw_output)

            for prefix in prefixes:
                for func, blocks in func_remarks.items():
                    checks = generate_check_lines(comment_marker, prefix, blocks)
                    remark_checks.setdefault(func, []).extend(checks)

        # Rebuild file.
        if is_mir:
            output_lines = update_mir_file(
                input_lines, remark_checks, all_remark_prefixes, note
            )
        else:
            output_lines = update_ll_file(
                input_lines, remark_checks, all_remark_prefixes, note
            )

        with open(test_path, "w") as f:
            for line in output_lines:
                f.write(line + "\n")

        print("Updated {}".format(test_path))


if __name__ == "__main__":
    main()
